# Files to process
FRONTEND_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'frontend', 'src')

def get_all_tsx_files():
    """Get all TSX files in the frontend src directory."""
    pattern = os.path.join(FRONTEND_DIR, '**', '*.tsx')
    return glob.glob(pattern, recursive=True)

def replace_emojis_in_file(filepath):
    """Replace emojis in a single file with Lucide icon components."""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    original = content
    used_icons = set()
    
    # Find all emojis in the file
    for emoji, icon_name in EMOJI_MAP.items():
        if emoji in content:
            used_icons.add(icon_name)
            # Replace emoji with icon component
            content = content.replace(emoji, f'<{icon_name} size={14} className="inline-block" />')
    
    if content == original:
        return False, set()
    
    # Add import for used icons
    if used_icons:
        # Check if there's already a lucide-react import
        import_pattern = r"from 'lucide-react'"
        existing_imports = re.search(r"import\s*\{([^}]+)\}\s*from\s*'lucide-react'", content)
        
        if existing_imports:
            # Add new icons to existing import
            current_imports = set(existing_imports.group(1).split(','))
            current_imports = {i.strip() for i in current_imports if i.strip()}
            all_icons = current_imports | used_icons
            sorted_icons = sorted(all_icons, key=lambda x: x.lower())
            new_import = f"import {{ {', '.join(sorted_icons)} }} from 'lucide-react'"
            content = content.replace(existing_imports.group(0), new_import)
        else:
            # Add new import line
            sorted_icons = sorted(used_icons, key=lambda x: x.lower())
            new_import = f"import {{ {', '.join(sorted_icons)} }} from 'lucide-react';\n"
            # Insert after the last import
            last_import = list(re.finditer(r"^import .+$", content, re.MULTILINE))
            if last_import:
                pos = last_import[-1].end()
                content = content[:pos] + '\n' + new_import + content[pos:]
            else:
                content = new_import + content
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    
    return True, used_icons

def main():
    files = get_all_tsx_files()
    total_replaced = 0
    total_icons = set()
    
    print(f"Found {len(files)} TSX files to process")
    
    for filepath in files:
        try:
            replaced, icons = replace_emojis_in_file(filepath)
            if replaced:
                rel_path = os.path.relpath(filepath, FRONTEND_DIR)
                print(f"  ✓ {rel_path} - icons: {', '.join(sorted(icons))}")
                total_replaced += 1
                total_icons |= icons
        except Exception as e:
            print(f"  ✗ Error processing {filepath}: {e}")
    
    print(f"\nDone! Processed {total_replaced} files with {len(total_icons)} unique icons")

if __name__ == '__main__':
    main()